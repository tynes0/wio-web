const print = 'use std::console as console;'
function program(body, imports = '', declarations = '') {
  return `${print}${imports ? `\n${imports}` : ''}\n\n${declarations ? `${declarations}\n\n` : ''}fn Entry() -> i32 {\n${body}\n    return 0;\n}\n`
}
function recipe(
  id,
  title,
  category,
  description,
  body,
  imports = '',
  declarations = '',
  output = '',
  note = '',
) {
  return {
    id,
    title,
    category,
    description,
    code: program(body, imports, declarations),
    output,
    note,
    filename: `${id}.wio`,
    kind: 'Single file',
    doc: 'std',
  }
}

